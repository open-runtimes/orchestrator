// Package mountagent is the node mount agent: a CSI node plugin that serves
// each mounting pod's workspace as an inline ephemeral volume, and an HTTP API
// through which that pod's sidecar asks for artifact mounts inside it. The
// mounts are performed on the node, so no container in the pod needs privilege
// (docs/design/node-mount-agent.md).
//
// The client half (Client) is what the sidecar uses in place of its in-pod
// kernel mounter; it is portable. The server half is Linux-only.
package mountagent

import (
	"crypto/sha256"
	"crypto/subtle"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sync"
)

// AttributeToken is the volume attribute carrying the volume's capability
// token. The mapper mints a random one per pod and gives the same value to the
// sidecar's environment; presenting it is what authorizes a mount request in
// that pod's workspace and nowhere else. The worker container sees neither.
const AttributeToken = "token"

// Volume is one published workspace.
type Volume struct {
	ID        string `json:"id"`
	Target    string `json:"target"`    // kubelet's publish path: the workspace as the pod sees it
	Data      string `json:"data"`      // the directory bound onto Target, owned by the agent
	TokenHash string `json:"tokenHash"` // hex sha256 of the token; the token itself is never stored
	Pod       string `json:"pod"`       // namespace/name, for logs
	PodUID    string `json:"podUid"`

	mu sync.Mutex // serializes mount operations within one workspace
}

func hashToken(token string) string {
	sum := sha256.Sum256([]byte(token))
	return hex.EncodeToString(sum[:])
}

// registry indexes published volumes by ID (for CSI) and by token hash (for
// the mount API). Records are persisted beside each volume's data so an agent
// restart keeps serving workspaces that kubelet published before it.
type registry struct {
	dir string // <state>/volumes

	mu      sync.RWMutex
	byID    map[string]*Volume
	byToken map[string]*Volume
}

func newRegistry(stateDir string) (*registry, error) {
	r := &registry{
		dir:     filepath.Join(stateDir, "volumes"),
		byID:    map[string]*Volume{},
		byToken: map[string]*Volume{},
	}
	if err := os.MkdirAll(r.dir, 0o700); err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(r.dir)
	if err != nil {
		return nil, err
	}
	for _, e := range entries {
		data, err := os.ReadFile(filepath.Join(r.dir, e.Name(), "volume.json"))
		if errors.Is(err, os.ErrNotExist) {
			continue // a publish that never finished; unpublish will clean it
		}
		if err != nil {
			return nil, err
		}
		v := &Volume{}
		if err := json.Unmarshal(data, v); err != nil {
			return nil, fmt.Errorf("volume record %s: %w", e.Name(), err)
		}
		r.byID[v.ID] = v
		r.byToken[v.TokenHash] = v
	}
	return r, nil
}

// volumeDir is where a volume's record and data live. CSI volume IDs for
// inline volumes are generated by kubelet; hash them so the directory name is
// always a single safe path component.
func (r *registry) volumeDir(id string) string {
	sum := sha256.Sum256([]byte(id))
	return filepath.Join(r.dir, hex.EncodeToString(sum[:16]))
}

func (r *registry) put(v *Volume) error {
	data, err := json.Marshal(v)
	if err != nil {
		return err
	}
	dir := r.volumeDir(v.ID)
	tmp := filepath.Join(dir, "volume.json.tmp")
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	if err := os.Rename(tmp, filepath.Join(dir, "volume.json")); err != nil {
		return err
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	r.byID[v.ID] = v
	r.byToken[v.TokenHash] = v
	return nil
}

func (r *registry) get(id string) *Volume {
	r.mu.RLock()
	defer r.mu.RUnlock()
	return r.byID[id]
}

// forToken resolves a presented token to its volume. The map is keyed by the
// token's hash, so the lookup never compares the secret itself; the final
// constant-time comparison only guards against a hash-map quirk.
func (r *registry) forToken(token string) *Volume {
	if len(token) < minTokenLen {
		return nil
	}
	h := hashToken(token)
	r.mu.RLock()
	v := r.byToken[h]
	r.mu.RUnlock()
	if v == nil || subtle.ConstantTimeCompare([]byte(v.TokenHash), []byte(h)) != 1 {
		return nil
	}
	return v
}

func (r *registry) remove(id string) error {
	r.mu.Lock()
	if v := r.byID[id]; v != nil {
		delete(r.byToken, v.TokenHash)
	}
	delete(r.byID, id)
	r.mu.Unlock()
	return os.RemoveAll(r.volumeDir(id))
}

// minTokenLen rejects tokens too short to be the 32 random bytes the mapper
// mints (64 hex characters).
const minTokenLen = 64
